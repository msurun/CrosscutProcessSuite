"""Cache DEV synthetic records of synth14 and the shifted generator as npz files.

Usage: python cache_synth.py <dir> <s14 first> <s14 last> <shift first> <shift last>. Dev seeds only
(synth14 <= 399, shifted <= 300); the final
seeds are generated by final.py in one run and appear in no other script.
"""

from __future__ import annotations

import concurrent.futures
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "exp14_stiction_classifier"))
import synth14  # noqa: E402
import synth_shift  # noqa: E402

KINDS, CASES, NOISES = "FL", ("stick", "sine", "square", "tuning"), ("low", "mid", "high")
DEV_S14_MAX, DEV_SHIFT_MAX = 399, 300  # final seeds (>= 500 / >= 1000) are never generated here


def record(job: tuple[str, str, str, str, int, str]) -> None:
    """Simulate one record and write <gen>_<kind>_<case>_<noise>_<seed>.npz."""
    gen, kind, case, noise, seed, folder = job
    rng = np.random.default_rng([seed, KINDS.index(kind), CASES.index(case), NOISES.index(noise)])
    if gen == "s14":
        sp, pv, op, label, k = synth14.simulate14(rng, kind, case)
        half = synth_shift._half_cycle(op)
    else:
        r = synth_shift.simulate_shift(rng, kind, case, noise)
        sp, pv, op, label, k, half = r.sp, r.pv, r.op, r.label, r.dt_factor, r.half_cycle_samples
    name = f"{gen}_{kind}_{case}_{noise}_{seed}.npz"
    np.savez(Path(folder) / name, sp=sp, pv=pv, op=op, label=float(label), k=k, half=half)


def main(folder: str, s14: range, shift: range) -> None:
    """Write all dev records."""
    Path(folder).mkdir(parents=True, exist_ok=True)
    jobs = [("s14", k, c, "mid", s, folder) for k in KINDS for c in CASES for s in s14]
    jobs += [
        ("shift", k, c, n, s, folder) for k in KINDS for c in CASES for n in NOISES for s in shift
    ]
    with concurrent.futures.ProcessPoolExecutor(max_workers=4) as pool:
        list(pool.map(record, jobs, chunksize=8))
    print(f"cached {len(jobs)} records")


if __name__ == "__main__":
    a, b, c, d = (int(x) for x in sys.argv[2:6])
    assert b <= DEV_S14_MAX and d <= DEV_SHIFT_MAX, "dev seeds only"
    main(sys.argv[1], range(a, b + 1), range(c, d + 1))
